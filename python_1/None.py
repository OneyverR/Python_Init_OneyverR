
# None significa "ninguno" o "nulo". En Python, None es un valor especial que representa la ausencia de un valor o un objeto. Se utiliza para indicar que una variable no tiene ningún valor asignado o que una función no devuelve ningún valor.

x =  None
print(x)  # Imprime None
print(type(x))  # Imprime <class 'NoneType'>, que es el tipo de dato de None

#Aclaracion: None no es lo mismo que False, 0 o una cadena vacía. None es un valor especial que indica la ausencia de un valor, mientras que False, 0 y una cadena vacía son valores válidos.

print(type("")) # Imprime <class 'str'>, que es el tipo de dato de una cadena de texto
print(type(0)) # Imprime <class 'int'>, que es el tipo de dato de un número entero
print(type(False)) # Imprime <class 'bool'>, que es el tipo de dato de un valor booleano
print(type([])) # Imprime <class 'list'>, que es el tipo de dato de una lista

